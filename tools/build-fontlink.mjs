/* Emit the first-paint font <link> for whatever families the directions use.

   The panel loads a family on demand when you pick it, but the panel is
   dev-only — postbuild deletes it. So a direction that names a family the
   head never requested renders a fallback in production, silently. Baking
   picked fonts into a direction without this step ships that bug.

   Scans every direction JSON plus the token defaults for --rx-font-* values,
   resolves each family against the Google catalogue for its real weights,
   and rewrites the block between the rx:fonts markers in index.html. */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const HTML = path.join(ROOT, 'site/index.html');
const CAT  = path.join(ROOT, 'site/public/remix/fonts.json');
const DIRS = path.join(ROOT, 'remix/directions');
const TOKENS = path.join(ROOT, 'site/assets/styles/remix-tokens.css');

const WANT = [300, 400, 500, 600, 700];               // what the page actually sets

const familyOf = (stack) =>
  String(stack).split(',')[0].trim().replace(/^["']|["']$/g, '');

const catalogue = new Map(
  (JSON.parse(fs.readFileSync(CAT, 'utf8')).fonts || []).map((f) => [f.family, f])
);

/* collect every family any direction can put on the page */
const families = new Set();
for (const f of fs.readdirSync(DIRS).filter((n) => n.endsWith('.json'))) {
  const d = JSON.parse(fs.readFileSync(path.join(DIRS, f), 'utf8'));
  for (const [k, v] of Object.entries(d.tokens || {})) {
    if (k.startsWith('--rx-font-')) families.add(familyOf(v));
  }
}
for (const m of fs.readFileSync(TOKENS, 'utf8').matchAll(/--rx-font-[\w-]+\s*:\s*([^;]+);/g)) {
  families.add(familyOf(m[1]));
}

/* keep only families Google actually serves — system stacks need no request */
const serve = [...families].filter((f) => catalogue.has(f)).sort();
const skipped = [...families].filter((f) => !catalogue.has(f)).sort();

const params = serve.map((fam) => {
  const have = catalogue.get(fam).weights.map(Number);
  const use = WANT.filter((w) => have.includes(w));
  const weights = (use.length ? use : have).join(';');
  return 'family=' + fam.replace(/ /g, '+') + ':wght@' + weights;
});

const href = 'https://fonts.googleapis.com/css2?' + params.join('&') + '&display=swap';
const block =
  '  <!-- rx:fonts — generated by tools/build-fontlink.mjs, do not hand-edit -->\n' +
  `  <link rel="stylesheet" href="${href}">\n` +
  '  <!-- /rx:fonts -->';

let html = fs.readFileSync(HTML, 'utf8');
const a = html.indexOf('  <!-- rx:fonts');
const b = html.indexOf('<!-- /rx:fonts -->');
if (a < 0 || b < 0) {
  console.error('FAIL: rx:fonts markers not found in site/index.html');
  process.exit(1);
}
const next = html.slice(0, a) + block + html.slice(b + '<!-- /rx:fonts -->'.length);
if (next === html) console.log('font link already current');
else { fs.writeFileSync(HTML, next); console.log('font link rewritten'); }

console.log(`  families requested: ${serve.length} — ${serve.join(', ')}`);
if (skipped.length) console.log(`  not in catalogue (system stack, no request): ${skipped.join(', ')}`);
if (href.length > 2000) console.log(`  WARNING: href is ${href.length} chars`);
